-- Диагностика схемы нативной 2SV в Jira DC 10.6.1 (PostgreSQL).
-- Все запросы read-only (SELECT), безопасны для выполнения на проде.
-- Рекомендуется выполнять через реплику Patroni, если она доступна для чтения.
--
-- ВАЖНО: Active Objects создаёт колонки как quoted UPPERCASE identifiers
-- (см. результат ШАГА 2: CREATED_AT, USER_KEY и т.д.). Если пишете свой запрос
-- к AO-таблице с перечислением колонок (не через SELECT *), их нужно брать
-- в двойные кавычки и в верхнем регистре — например "USER_KEY", а не user_key,
-- иначе Postgres свернёт имя в нижний регистр и колонку "не найдёт".
--
-- Порядок использования:
--   1) Выполнить ШАГ 1, найти реальное имя AO-таблицы.
--   2) Подставить найденное имя в ШАГ 2 и ШАГ 3.
--   3) Обновить константы TABLE/USER_KEY_COLUMN в TwoSVStatusChecker.java по результату.

-- ==========================================================================
-- ШАГ 1. Найти таблицу(ы), связанные с TOTP / 2SV / 2FA.
-- ==========================================================================
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND (
        table_name ILIKE '%totp%'
     OR table_name ILIKE '%2sv%'
     OR table_name ILIKE '%2fa%'
     OR table_name ILIKE '%ED669C%'
     OR table_name ILIKE '%mfa%'
  )
ORDER BY table_name;

-- ==========================================================================
-- ШАГ 2. Структура найденной таблицы (замените <TABLE_NAME>).
-- ==========================================================================
SELECT column_name, data_type, is_nullable
FROM information_schema.columns
WHERE table_schema = 'public'
  AND table_name = '<TABLE_NAME>'
ORDER BY ordinal_position;

-- ==========================================================================
-- ШАГ 3. Проверить, какая колонка хранит идентификатор пользователя
-- и в каком формате (userkey vs username vs id) — сверить с cwd_user/app_user.
-- Замените <TABLE_NAME> и <USER_KEY_COLUMN> по результатам ШАГА 2.
-- LIMIT 5 — не тянем всю таблицу, только для просмотра формата значений.
-- ==========================================================================
SELECT *
FROM "<TABLE_NAME>"
LIMIT 5;

-- Сверка формата идентификатора пользователя (в Jira DC user key обычно
-- совпадает с cwd_user.user_name или cwd_user.lower_user_name — проверить оба варианта):
SELECT cu.id, cu.user_name, cu.lower_user_name
FROM cwd_user cu
LIMIT 5;

-- ==========================================================================
-- ШАГ 4. Контрольный подсчёт: сколько пользователей уже зарегистрировали 2SV
-- (не более одного такого запроса за раз — таблица потенциально большая).
-- Замените <TABLE_NAME>.
-- ==========================================================================
SELECT COUNT(*) AS enrolled_users
FROM "<TABLE_NAME>";

-- ==========================================================================
-- ШАГ 5 (опционально). Если ШАГ 1 не нашёл ничего очевидного — общий список
-- всех AO-таблиц плагинов для ручного просмотра (обычно их немного).
-- ==========================================================================
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_name LIKE 'AO\_%' ESCAPE '\'
ORDER BY table_name;
